void font_draw_char(uint16_t *fb, int x, int y, char c, uint16_t color, uint8_t scale) {
    if (scale == 0) scale = 1;
    if (c < 0x21 || c > 0x7E) return;

    const uint8_t *glyph = s_stealth57[(uint8_t)(c - 0x21)];
    for (int cx = 0; cx < FONT_GLYPH_W; cx++) {
        uint8_t col_bits = glyph[cx];
        for (int cy = 0; cy < FONT_GLYPH_H; cy++) {
            if ((col_bits & (1u << cy)) == 0) continue;
            int px0 = x + cx * scale;
            int py0 = y + cy * scale;
            for (int dy = 0; dy < scale; dy++) {
                int py = py0 + dy;
                if (py < 0 || py >= LCD_HEIGHT) continue;
                for (int dx = 0; dx < scale; dx++) {
                    int px = px0 + dx;
                    if (px < 0 || px >= LCD_WIDTH) continue;
                    fb[py * LCD_WIDTH + px] = color;
                }
            }
        }
    }
}

void font_draw_str(uint16_t *fb, int x, int y, const char *str, uint16_t color, uint8_t scale) {
    if (!str) return;
    if (scale == 0) scale = 1;
    int step = FONT_ADVANCE_X * scale;
    int cur_x = x;
    while (*str) {
        font_draw_char(fb, cur_x, y, *str, color, scale);
        cur_x += step;
        str++;
    }
}

int font_measure_str(const char *str, uint8_t scale) {
    if (!str || !*str) return 0;
    if (scale == 0) scale = 1;
    int len = 0;
    while (str[len]) len++;
    return (len * FONT_ADVANCE_X - FONT_SPACING_X) * scale;
}
